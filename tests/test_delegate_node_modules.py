def _probe_offline_pnpm():
    if not shutil.which("pnpm"):
        return False, None, None, "pnpm not installed"
    ch = Path(os.environ.get("COREPACK_HOME") or (Path(os.environ.get("XDG_CACHE_HOME") or (Path.home() / ".cache")) / "node/corepack"))
    env = {
        **os.environ,
        "COREPACK_HOME": str(ch),
        "COREPACK_ENABLE_DOWNLOAD_PROMPT": "0",
        "COREPACK_ENABLE_NETWORK": "0",
    }
    try:
        with tempfile.TemporaryDirectory() as tmp:
            res = subprocess.run(
                ["pnpm", "--version"],
                cwd=tmp,
                env=env,
                stdin=subprocess.DEVNULL,
                capture_output=True,
                text=True,
                timeout=5,
            )
            if res.returncode == 0:
                return True, None, ch, ""
            v1_pnpm = ch / "v1/pnpm"
            if v1_pnpm.is_dir():
                for cand in sorted((p.name for p in v1_pnpm.iterdir() if p.is_dir()), reverse=True):
                    (Path(tmp) / "package.json").write_text(json.dumps({"packageManager": f"pnpm@{cand}"}))
                    res2 = subprocess.run(
                        ["pnpm", "--version"],
                        cwd=tmp,
                        env=env,
                        stdin=subprocess.DEVNULL,
                        capture_output=True,
                        text=True,
                        timeout=5,
                    )
                    if res2.returncode == 0:
                        return True, f"pnpm@{cand}", ch, ""
    except (OSError, subprocess.SubprocessError):
        pass
    return False, None, ch, "pnpm unavailable offline (corepack shim has no cached pnpm version)"


PNPM_OK, PNPM_PACKAGE_MANAGER, PNPM_COREPACK_HOME, PNPM_SKIP_REASON = _probe_offline_pnpm()


def make_tiny_tarball(path: Path) -> Path:
    with tarfile.open(path, "w:gz") as tf:
        for name, data, mode in (
            ("package/package.json",
             json.dumps({"name": "tiny", "version": "1.0.0", "main": "index.js", "bin": {"tiny": "bin.js"}}).encode(),
             0o644),
            ("package/index.js", b"module.exports = 1;\n", 0o644),
            ("package/bin.js", b"#!/usr/bin/env node\nconsole.log('tiny-ok');\n", 0o755),
        ):
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mode = mode
            tf.addfile(info, io.BytesIO(data))
    return path


class DelegateNodeModulesIsolationTests(unittest.TestCase):
    fake_pi = fixtures.DelegateTests.fake_pi
    cli = fixtures.DelegateTests.cli
    outcome = fixtures.DelegateTests.outcome
    repo = fixtures.DelegateTests.repo

    def setUp(self):
        fixtures.DelegateTests.setUp(self)
        if PNPM_COREPACK_HOME is not None:
            self.env["COREPACK_HOME"] = str(PNPM_COREPACK_HOME)
        self.env["COREPACK_ENABLE_DOWNLOAD_PROMPT"] = "0"
        self.env["COREPACK_ENABLE_NETWORK"] = "0"

    def pnpm_workspace_repo(self, extra_files=None):
        tgz = make_tiny_tarball(self.work / "tiny-1.0.0.tgz")
        root_pkg = {"name": "root", "private": True, "version": "1.0.0"}
        if PNPM_PACKAGE_MANAGER:
            root_pkg["packageManager"] = PNPM_PACKAGE_MANAGER
        files = {
            ".gitignore": "node_modules\n",
            "pnpm-workspace.yaml": "packages:\n  - apps/web\n  - packages/pkg\n",
            "package.json": json.dumps(root_pkg),
            "packages/pkg/package.json": json.dumps({"name": "@demo/pkg", "version": "1.0.0", "main": "index.js"}),
            "packages/pkg/index.js": "module.exports = 42;\n",
            "apps/web/package.json": json.dumps({
                "name": "@demo/web",
                "version": "1.0.0",
                "dependencies": {"@demo/pkg": "workspace:*", "tiny": f"file:{tgz}"},
            }),
            "apps/web/note.txt": "old\n",
        }
        if extra_files:
            files.update(extra_files)
        repo = self.repo(files)
        store = self.work / "pnpm-store"
        env = dict(self.env, npm_config_store_dir=str(store), PNPM_HOME=str(self.work / "pnpm-home"))
        install = subprocess.run(
            ["pnpm", "install", "--offline", "--store-dir", str(store)],
            cwd=repo,
            env=env,
            stdin=subprocess.DEVNULL,
            capture_output=True,
            text=True,
            timeout=30,
        )
        self.assertEqual(install.returncode, 0, install.stdout + install.stderr)
        return repo, store

    @unittest.skipUnless(PNPM_OK, PNPM_SKIP_REASON)
    def test_colleague_cannot_symlink_source_node_modules_and_rewrite_source_via_pnpm(self):
        repo, store = self.pnpm_workspace_repo()
        before_tiny = os.readlink(repo / "apps/web/node_modules/tiny")
        before_pkg = os.readlink(repo / "apps/web/node_modules/@demo/pkg")
        code_file = self.work / "ln-code"
        source_nm = shlex.quote(str(repo / "apps/web/node_modules"))
        cmd = f"ln -s {source_nm} apps/web/node_modules"
        pre = (
            f"bash -c {shlex.quote(cmd)}; echo $? > {shlex.quote(str(code_file))}; "
            f"pnpm install --offline --store-dir {shlex.quote(str(store))}"
        )
        self.fake_pi([fixtures.answer("done"), fixtures.SETTLED], pre=pre)
        result = self.cli("run", "--worktree", "--workdir", repo, "install deps")
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(code_file.read_text().strip(), "77")
        self.assertEqual(os.readlink(repo / "apps/web/node_modules/tiny"), before_tiny)
        self.assertEqual(os.readlink(repo / "apps/web/node_modules/@demo/pkg"), before_pkg)

    @unittest.skipUnless(PNPM_OK, PNPM_SKIP_REASON)
    def test_source_watch_rejects_node_modules_symlink_leak_even_with_worktree_edits(self):
        repo, store = self.pnpm_workspace_repo()
        # Bypass bash source_guard via python os.symlink, run pnpm so source/apps/web/node_modules
        # gets rewritten to point into the worktree, remove the worktree symlink, and edit a tracked file.
        py = shlex.quote(f"import os; os.symlink({str(repo / 'apps/web/node_modules')!r}, 'apps/web/node_modules')")
        bypass = (
            f"python3 -c {py} && "
            f"pnpm install --offline --store-dir {shlex.quote(str(store))} && "
            f"rm apps/web/node_modules && "
            f"echo changed > apps/web/note.txt"
        )
        self.fake_pi([fixtures.answer("done"), fixtures.SETTLED], pre=bypass)
        result = self.cli("run", "--worktree", "--workdir", repo, "task")
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        state = self.outcome(result)
        self.assertEqual(state["state"], "rejected")
        self.assertIn("apps/web/node_modules", state["sourceWriteViolation"])
        self.assertIn("apps/web/node_modules", state["sourceWorkspaceChanges"])

    @unittest.skipUnless(PNPM_OK, PNPM_SKIP_REASON)
    def test_pre_accept_blocks_worktree_node_modules_symlink_to_source(self):
        repo, store = self.pnpm_workspace_repo()
        before_tiny = os.readlink(repo / "apps/web/node_modules/tiny")
        before_pkg = os.readlink(repo / "apps/web/node_modules/@demo/pkg")
        py = shlex.quote(f"import os; os.symlink({str(repo / 'apps/web/node_modules')!r}, 'apps/web/node_modules')")
        bypass = (
            f"python3 -c {py} && "
            f"echo changed > apps/web/note.txt"
        )
        self.fake_pi([fixtures.answer("done"), fixtures.SETTLED], pre=bypass)
        result = self.cli(
            "run", "--worktree", "--workdir", repo,
            "--accept", f"pnpm install --offline --store-dir {shlex.quote(str(store))}",
            "task",
        )
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        state = self.outcome(result)
        self.assertEqual(state["state"], "rejected")
        self.assertIn("apps/web/node_modules", state["sourceWriteViolation"])
        self.assertEqual(os.readlink(repo / "apps/web/node_modules/tiny"), before_tiny)
        self.assertEqual(os.readlink(repo / "apps/web/node_modules/@demo/pkg"), before_pkg)

    def test_worktree_link_and_share_refuse_node_modules(self):
        self.fake_pi([fixtures.answer("done"), fixtures.SETTLED])
        repo = self.repo({
            "a.txt": "old\n",
            ".gitignore": "node_modules\n",
            ".delegate.json": json.dumps({"worktree": {"link": ["apps/web/node_modules"]}}),
        })
        (repo / "apps/web/node_modules").mkdir(parents=True)
        link_res = self.cli("start", "--worktree", "--workdir", repo, "task")
        self.assertEqual(link_res.returncode, 2, link_res.stdout + link_res.stderr)
        self.assertIn("node_modules", link_res.stderr)

        (repo / ".delegate.json").write_text("{}")
        share_res = self.cli("start", "--worktree", "--workdir", repo,
                             "--share", str(repo / "apps/web/node_modules"), "task")
        self.assertEqual(share_res.returncode, 2, share_res.stdout + share_res.stderr)
        self.assertIn("node_modules", share_res.stderr)

    @unittest.skipUnless(PNPM_OK, PNPM_SKIP_REASON)
    def test_worktree_pnpm_install_stays_isolated_from_source(self):
        repo, store = self.pnpm_workspace_repo()
        before_tiny = os.readlink(repo / "apps/web/node_modules/tiny")
        before_pkg = os.readlink(repo / "apps/web/node_modules/@demo/pkg")
        self.fake_pi(
            [fixtures.answer("done"), fixtures.SETTLED],
            pre=f"pnpm install --offline --store-dir {shlex.quote(str(store))} && echo updated > apps/web/note.txt",
        )
        result = self.cli("run", "--worktree", "--workdir", repo, "task")
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        state = self.outcome(result)
        self.assertEqual(state["state"], "answered")
        self.assertNotIn("sourceWriteViolation", state)
        self.assertNotIn("sourceWorkspaceChanges", state)
        self.assertEqual(os.readlink(repo / "apps/web/node_modules/tiny"), before_tiny)
        self.assertEqual(os.readlink(repo / "apps/web/node_modules/@demo/pkg"), before_pkg)

    def test_bash_guard_refuses_relative_ln_into_source(self):
        repo = self.repo({"apps/web/a": "old\n", ".gitignore": "node_modules\n"})
        (repo / "apps/web/node_modules").mkdir(parents=True)
        code_file = self.work / "rel-ln-code"
        # Compute relative path from worktree/apps/web to repo/apps/web/node_modules at runtime via python,
        # then invoke `ln -s <rel> apps/web/node_modules` inside bash so the command text lacks the literal source path.
        pre = (
            f"rel=$(python3 -c 'import os,sys; print(os.path.relpath(sys.argv[1], os.path.abspath(\"apps/web\")))' "
            f"{shlex.quote(str(repo / 'apps/web/node_modules'))}); "
            f"bash -c \"ln -s $rel apps/web/node_modules\"; echo $? > {shlex.quote(str(code_file))}"
        )
        self.fake_pi([fixtures.answer("done"), fixtures.SETTLED], pre=pre)
        result = self.cli("run", "--worktree", "--workdir", repo, "task")
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(code_file.read_text().strip(), "77")
        state = self.outcome(result)
        self.assertFalse((Path(state["worktree"]) / "apps/web/node_modules").is_symlink())


